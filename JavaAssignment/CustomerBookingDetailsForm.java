    public void CustomerBookingDetailsForm(String selectedid, String username) {
        initComponents();
        setLocationRelativeTo(null);
        jtxtname.setText(selectedid);
        
        //Load and store all the car data into an arraylist
        ArrayList<String> cardata = LoadData.cardetailsdata();
        
        //Create an arraylist to append the new selected car data
        ArrayList<String> data = new ArrayList<String>();

        //Load out all the data of the car which has the same id with the String selectedid
        int index = 0, count = 0;
        while (index < cardata.size()) {
            if (cardata.get(index).equals(username)) {
                count = index;
                break;
            }
            index++;
        }
        //One car booking data contains 8 different data so repeat steps 8 times.
        for (int i = 0; i != 8; i++) {
            data.add(cardata.get(count));
            count++;
        }
        
        
        jtxtCarBrand.setText(data.get(0));
        jtxtCarModel.setText(data.get(1));
        jtxtCarType.setText(data.get(2));
        jtxtCarPlateNo.setText(data.get(3));
        jtxtSeats.setText(data.get(4));
        jtxtCarColour.setText(data.get(5));
        jtxtFeulType.setText(data.get(6));
        jtxtPricePerDay.setText(data.get(7));
        
        //Set date format to yyyy/mm/dd to maintain an correct order throughout entire process
        jtxtstartdate.setDateFormatString("yyyy/MM/dd");
        jtxtenddate.setDateFormatString("yyyy/MM/dd");
        
        //Set date range for users
        Calendar cal = Calendar.getInstance();
        cal.add(Calendar.DATE, 3);
        //Create date variable to get time.
        Date mindate = cal.getTime();
        cal.add(Calendar.YEAR, 1);
        Date maxdate = cal.getTime();
        //Set minimum and maximum date range
        jtxtstartdate.setDate(mindate);
        jtxtstartdate.setSelectableDateRange(mindate, maxdate);
        jtxtenddate.setDate(mindate);
        //jtxtenddate.setSelectableDateRange(mindate, maxdate);
    }

