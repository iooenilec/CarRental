    private void jbtnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnConfirmActionPerformed
        // TODO add your handling code here:
            //add booking from all input
                
            //Set date format
                SimpleDateFormat DateFormat = new SimpleDateFormat("yyyy/MM/dd");

                //Get start date input and convert into string.
                String startdate = DateFormat.format(jtxtstartdate.getDate());

                //Get end date input and convert into string.
                String enddate = DateFormat.format(jtxtenddate.getDate());
                
                SimpleDateFormat DateFormat1 = new SimpleDateFormat("yyyyMMdd");

                //Get start date input and convert into string.
                String startdate1 = DateFormat1.format(jtxtstartdate.getDate());
                
                String bookingid = "B"+jtxtCarPlateNo.getText()+jtxtname.getText()+startdate1;
                
            if (bookingid.isEmpty() || jtxtname.getText().isEmpty() || jtxtCarPlateNo.getText().isEmpty() || startdate.isEmpty() || enddate.isEmpty() || jtxtPricePerDay.getText().isEmpty() || jtxtprice.getText().isEmpty() || jtxtCardNo.getText().isEmpty() || jtxtCVV.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Please fill in the blank.");
            }
            else {                                
                Booking.addbookingdetails(bookingid, jtxtname.getText(), jtxtCarPlateNo.getText(), startdate, enddate, jtxtPricePerDay.getText(), jtxtprice.getText(), jtxtCardNo.getText(), jtxtCVV.getText(), "Pending");

                //Once modification is successful then display Successfully Modified and prompt the Search Booking List Form to the user.
                JOptionPane.showMessageDialog(this, "Successfully Added.");
                String username = jtxtname.getText();
                CustomerMain brf = new CustomerMain();
                brf.CustomerMain(username);
                brf.setLocationRelativeTo(null);
                brf.setVisible(true);
                dispose();
            }

    }//GEN-LAST:event_jbtnConfirmActionPerformed

