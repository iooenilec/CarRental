    public void CustomerEditProfile(String selectedid) {
        initComponents();
        setLocationRelativeTo(null);
        //jtxtusername.setText(selectedid);
        jtxtname1.setText(selectedid);
        
        //Load and store all the booking record data into an arraylist
        ArrayList<String> bookingdata = LoadData.customerdata(selectedid);
        
        //Create an arraylist to append the new selected booking data
        ArrayList<String> data = new ArrayList<String>();

        //Load out all the data of the booking which has the same id with the String selectedid
        int index = 0, count = 0;
        while (index < bookingdata.size()) {
            if (bookingdata.get(index).equals(selectedid)) {
                count = index;
                break;
            }
            index++;
        }
        //One Room booking data contains 10 different data so repeat steps 10 times.
        for (int i = 0; i != 7; i++) {
            data.add(bookingdata.get(count));
            count++;
        }
        
        jtxtusername.setText(data.get(0));
        jtxtpassword.setText(data.get(1));
        jtxtname.setText(data.get(2));
        jtxtcitizenship.setText(data.get(3));
        jtxtic.setText(data.get(4));
        jtxtnumber.setText(data.get(5));
        jtxtemail.setText(data.get(6));
    }



