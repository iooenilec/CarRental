    private void jbtnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnSaveActionPerformed
        // TODO add your handling code here:
        if (jtxtusername.getText().isEmpty() || jtxtpassword.getText().isEmpty() || jtxtname.getText().isEmpty() || jtxtcitizenship.getText().isEmpty() || jtxtic.getText().isEmpty() || jtxtnumber.getText().isEmpty() || jtxtemail.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in the blank.");
        }else{
            //Modify booking from all input
            Booking.modifyprofile(jtxtusername.getText(), jtxtpassword.getText(), jtxtname.getText(), jtxtcitizenship.getText(), jtxtic.getText(), jtxtnumber.getText(), jtxtemail.getText());
            
            //Once modification is successful then display Successfully Modified and prompt the Search Booking List Form to the user.
            JOptionPane.showMessageDialog(this, "Successfully Modified.");
            String username = jtxtname1.getText();
            CustomerMain brf = new CustomerMain();
            brf.CustomerMain(username);
            brf.setLocationRelativeTo(null);
            brf.setVisible(true);
            dispose();
        }

    }//GEN-LAST:event_jbtnSaveActionPerformed

